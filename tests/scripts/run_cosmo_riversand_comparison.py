#!/usr/bin/env python3
"""Phase-5 riversand basin comparison harness (cosmo plan 5b / 6c(B)).

This script follows the same "download -> run -> delete" pattern as the other
`cosmo_realworld` tools, but targets a small starter subset for the riversand
cross-check.

Current scope:
  - fetch DEM keylessly with lsdtt-fetch-raster
  - run lsdtt-cosmo-tool inversion
  - join selected sample(s) against riversand erosion-rate output
  - freeze/check a tracked summary CSV

riversand invocation is intentionally flexible:
  - built-in mode (default): uses riversand + lsdtt-basin-extraction
  - pass `--riversand-csv` if you ran riversand out-of-band
  - or pass `--riversand-cmd` with placeholders to run it from this harness

Placeholders accepted in --riversand-cmd:
  {dataset} {workdir} {dem} {outcsv} {points}
"""

from __future__ import annotations

import argparse
import csv
import datetime
import shlex
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import run_cosmo_validation as rcv

EXIT_OK = 0
EXIT_FAIL = 1
EXIT_SKIP = 77

CHECK_REL_TOL = 0.02
SUMMARY_FIELDS = [
    "sample_name",
    "lsdtt_erate_gcm2yr",
    "riversand_erate_gcm2yr",
    "pct_diff_lsdtt_minus_riversand",
    "scheme",
    "dataset",
    "run_date_utc",
    "git_sha",
]


def _published_dir(cli_value: str | None) -> Path:
    return Path(cli_value) if cli_value else rcv.default_published_dir()


def riversand_available() -> bool:
    try:
        __import__("riversand")
        return True
    except Exception:  # noqa: BLE001 - dependency probe only
        return False


def preflight_dataset(dataset: str, published_dir: Path) -> tuple[dict, list]:
    manifest = rcv.load_manifest(dataset, published_dir)
    samples = rcv.read_sample_table(published_dir / manifest["sample_table"])
    if not samples:
        raise ValueError(f"sample table for {dataset} has no rows")
    return manifest, samples


def read_csv_with_comments(path: Path) -> list:
    with open(path, newline="") as f:
        lines = [ln for ln in f if not ln.lstrip().startswith("#")]
    return list(csv.DictReader(lines))


def read_erate_csv(path: Path) -> dict:
    with open(path, newline="") as f:
        return {r["sample_name"]: r for r in csv.DictReader(f)}


def read_frozen_summary(path: Path) -> dict:
    if not path.is_file():
        return {}
    return {r["sample_name"]: r for r in read_csv_with_comments(path)}


def write_frozen_summary(path: Path, rows: list, dataset: str, scheme: str) -> None:
    now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    sha = rcv.git_sha()
    with open(path, "w", newline="") as f:
        f.write("# Phase 5 riversand comparison frozen summary.\n")
        f.write("# Generated by tests/scripts/run_cosmo_riversand_comparison.py --freeze.\n")
        f.write("# Comparison sign: 100*(lsdtt - riversand)/riversand.\n")
        f.write(f"# Run: dataset={dataset} scheme={scheme} ; git {sha} ; utc {now}\n")
        w = csv.DictWriter(f, fieldnames=SUMMARY_FIELDS)
        w.writeheader()
        for r in rows:
            w.writerow({k: r.get(k, "") for k in SUMMARY_FIELDS})


def check_against_frozen(rows: list, frozen_path: Path) -> int:
    frozen = read_frozen_summary(frozen_path)
    if not frozen:
        print(f"CHECK: no frozen summary at {frozen_path}; run once with --freeze")
        return EXIT_FAIL

    ok = True
    for r in rows:
        name = r["sample_name"]
        ref = frozen.get(name)
        if ref is None:
            print(f"[CHECK][FAIL] {name}: not found in frozen summary")
            ok = False
            continue
        new_e = float(r["lsdtt_erate_gcm2yr"])
        ref_e = float(ref["lsdtt_erate_gcm2yr"])
        rel = abs(new_e - ref_e) / ref_e if ref_e else abs(new_e - ref_e)
        if rel > CHECK_REL_TOL:
            print(f"[CHECK][FAIL] {name}: lsdtt new={new_e:.8g} frozen={ref_e:.8g} rel={rel:.3g}")
            ok = False

        new_r = float(r["riversand_erate_gcm2yr"])
        ref_r = float(ref["riversand_erate_gcm2yr"])
        rel_r = abs(new_r - ref_r) / ref_r if ref_r else abs(new_r - ref_r)
        if rel_r > CHECK_REL_TOL:
            print(f"[CHECK][FAIL] {name}: riversand new={new_r:.8g} frozen={ref_r:.8g} rel={rel_r:.3g}")
            ok = False

    missing = set(frozen.keys()) - {r["sample_name"] for r in rows}
    if missing:
        print(f"[CHECK][FAIL] frozen samples absent from this run: {', '.join(sorted(missing))}")
        ok = False

    print(f"CHECK: {'PASS' if ok else 'FAIL'} (tol {CHECK_REL_TOL:.0%}, {len(rows)} rows)")
    return EXIT_OK if ok else EXIT_FAIL


def choose_samples(all_samples: list, wanted: list[str]) -> list:
    by_name = {s["sample_name"]: s for s in all_samples}
    out = []
    for w in wanted:
        s = by_name.get(w)
        if s is None:
            raise ValueError(f"requested sample '{w}' not found in sample table")
        out.append(s)
    return out


def load_riversand_rows(path: Path, key_col: str, rate_col: str) -> dict[str, float]:
    if not path.is_file():
        raise FileNotFoundError(f"riversand csv not found: {path}")
    rows = read_csv_with_comments(path)
    out: dict[str, float] = {}
    for r in rows:
        if key_col not in r or rate_col not in r:
            continue
        k = str(r[key_col]).strip()
        if not k:
            continue
        out[k] = float(r[rate_col])
    return out


def sample_elevation_m(sample: dict) -> float:
    for k in ("mean_elevation_m", "elevation_ave_m", "elevation_m"):
        if k in sample and str(sample[k]).strip() != "":
            return float(sample[k])
    raise ValueError(f"sample {sample.get('sample_name', '<unknown>')} has no elevation column")


def write_one_point_csv(sample: dict, out_csv: Path) -> None:
    fields = ["sample_name", "latitude", "longitude", "Be10_CONC", "Be10_uncertainty", "standardisation"]
    with open(out_csv, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerow({
            "sample_name": sample["sample_name"],
            "latitude": sample["latitude"],
            "longitude": sample["longitude"],
            "Be10_CONC": sample["Be10_CONC"],
            "Be10_uncertainty": sample["Be10_uncertainty"],
            "standardisation": "07KNSTD",
        })


def run_basin_extraction_for_sample(
    basin_exe: Path,
    sample: dict,
    dem_path: Path,
    workdir: Path,
    threshold_px: int,
) -> Path:
    sname = sample["sample_name"]
    sdir = workdir / f"riversand_{sname}"
    sdir.mkdir(parents=True, exist_ok=True)
    pt_csv = sdir / "point.csv"
    write_one_point_csv(sample, pt_csv)

    dem_local = sdir / dem_path.name
    if not dem_local.exists():
        try:
            dem_local.symlink_to(dem_path)
        except Exception:
            shutil.copy2(dem_path, dem_local)

    pfile = sdir / "basin.param"
    pfile.write_text(
        "\n".join(
            [
                f"read_path: {sdir}",
                f"write_path: {sdir}",
                f"read_fname: {dem_local.name}",
                "write_fname: basin",
                f"threshold_contributing_pixels: {threshold_px}",
                "select_basins_from_outlets: true",
                f"basin_outlet_file: {pt_csv.name}",
                "basin_outlet_snapping_method: expanding_square",
                f"basin_outlet_contributing_pixels_threshold: {threshold_px}",
                "basin_outlet_max_search_radius_pixels: 100",
                "write_basin_outlines: true",
                "write_basin_outlines_as_polygon: true",
                "basin_outlines_output_format: gpkg",
            ]
        )
        + "\n"
    )
    subprocess.run([str(basin_exe), str(sdir), pfile.name], check=True, cwd=str(sdir))

    poly = sdir / "basin_junction_basin_polygons.gpkg"
    if not poly.is_file():
        raise RuntimeError(f"basin extraction failed for {sname}: polygon file not found ({poly})")
    return poly


def infer_basin_exe(args) -> Path | None:
    if args.basin_exe:
        return Path(args.basin_exe)
    if args.exe:
        candidate = Path(args.exe).with_name("lsdtt-basin-extraction")
        if candidate.is_file():
            return candidate
    return None


def run_riversand_internal(
    samples: list,
    dem_path: Path,
    workdir: Path,
    basin_exe: Path,
    threshold_px: int,
    bins_m: int,
    scaling: str,
) -> Path:
    try:
        from riversand import Riversand
    except Exception as exc:  # noqa: BLE001 - optional dependency
        raise RuntimeError(f"riversand import failed: {exc}")

    rows = []
    for s in samples:
        poly = run_basin_extraction_for_sample(basin_exe, s, dem_path, workdir, threshold_px)
        rs = Riversand(path=str(poly.parent))
        rs.add_raster(dem_path.name, "elevation")
        rs.add_catchments(poly.name)
        rs.add_samples({
            "name": s["sample_name"],
            "latitude": float(s["latitude"]),
            "longitude": float(s["longitude"]),
            "elevation": sample_elevation_m(s),
            "press_flag": "std",
            "thickness": 0.0,
            "density": 2.65,
            "shielding": 1,
            "nuclide": "Be-10",
            "mineral": "quartz",
            "N": float(s["Be10_CONC"]),
            "delN": float(s["Be10_uncertainty"]),
            "standardization": "07KNSTD",
        })
        out = rs.process_single_catchment(
            bins=float(bins_m),
            scaling=scaling,
            shielding=1,
            verbose=False,
        )
        e_cm_yr = float(out.iloc[0]["E"])
        rows.append({
            "sample_name": s["sample_name"],
            "riversand_erate_gcm2yr": 2.65 * e_cm_yr,
        })

    out_csv = workdir / "riversand_output.csv"
    with open(out_csv, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["sample_name", "riversand_erate_gcm2yr"])
        w.writeheader()
        for r in rows:
            w.writerow({
                "sample_name": r["sample_name"],
                "riversand_erate_gcm2yr": f"{r['riversand_erate_gcm2yr']:.10g}",
            })
    return out_csv


def run_self_test(args) -> int:
    pdir = _published_dir(args.published_dir)
    manifest, samples = preflight_dataset("dethier2014", pdir)

    workdir = Path(tempfile.mkdtemp(prefix="cosmo_riversand_selftest_"))
    marker = workdir / "marker.txt"
    marker.write_text("ok\n")
    shutil.rmtree(workdir, ignore_errors=True)
    cleaned = not workdir.exists()

    ok = manifest.get("dataset") == "dethier2014" and len(samples) > 0 and cleaned
    print("SELFTEST:", "PASS" if ok else "FAIL")
    return EXIT_OK if ok else EXIT_FAIL


def run_mode(args) -> int:
    pdir = _published_dir(args.published_dir)
    dataset = args.dataset
    if dataset == "all":
        print("FAIL: this harness currently supports one dataset per run")
        return EXIT_FAIL

    manifest, samples_all = preflight_dataset(dataset, pdir)
    wanted = [x.strip() for x in args.samples.split(",") if x.strip()]
    samples = choose_samples(samples_all, wanted)
    print(f"[{dataset}] selected {len(samples)} sample(s): {', '.join(wanted)}")

    if not args.fetch_exe or not args.exe:
        print("FAIL: both --exe and --fetch-exe are required")
        return EXIT_FAIL

    workdir = Path(tempfile.mkdtemp(prefix=f"cosmo_riversand_{dataset}_"))
    print(f"[{dataset}] working directory: {workdir}")
    try:
        dem_path = rcv.fetch_dem(Path(args.fetch_exe), manifest, workdir)
        print(f"[{dataset}] DEM fetched: {dem_path} ({dem_path.stat().st_size} bytes)")

        points_csv = rcv.write_crn_input(samples, workdir)
        lsdtt_csv = rcv.run_cosmo_tool(
            Path(args.exe),
            dem_path,
            samples,
            workdir,
            run_params=manifest.get("run_params") or {},
        )
        lsdtt_rows = read_erate_csv(lsdtt_csv)

        rs_csv: Path | None = None
        if args.riversand_csv:
            rs_csv = Path(args.riversand_csv)
        elif args.riversand_cmd:
            rs_csv = workdir / "riversand_output.csv"
            cmd = args.riversand_cmd.format(
                dataset=dataset,
                workdir=str(workdir),
                dem=str(dem_path),
                outcsv=str(rs_csv),
                points=str(points_csv),
            )
            subprocess.run(shlex.split(cmd), check=True, cwd=str(workdir))
        else:
            if not riversand_available():
                print("SKIP: riversand is not installed; provide --riversand-csv or install riversand")
                return EXIT_SKIP
            basin_exe = infer_basin_exe(args)
            if basin_exe is None or not basin_exe.is_file():
                print(
                    "SKIP: built-in riversand mode needs lsdtt-basin-extraction; "
                    "set --basin-exe or provide --riversand-csv/--riversand-cmd"
                )
                return EXIT_SKIP
            rs_csv = run_riversand_internal(
                samples=samples,
                dem_path=dem_path,
                workdir=workdir,
                basin_exe=basin_exe,
                threshold_px=args.basin_threshold_pixels,
                bins_m=args.riversand_bins_m,
                scaling=args.riversand_scaling,
            )

        rs = load_riversand_rows(Path(rs_csv), args.riversand_key_col, args.riversand_rate_col)
        out_rows = []
        for s in samples:
            name = s["sample_name"]
            if name not in lsdtt_rows:
                raise RuntimeError(f"lsdtt output missing selected sample {name}")
            if name not in rs:
                raise RuntimeError(
                    f"riversand output missing selected sample {name} "
                    f"(key_col={args.riversand_key_col})"
                )
            le = float(lsdtt_rows[name]["apparent_eff_e_g_cm2_yr"])
            re = float(rs[name])
            pct = 100.0 * (le - re) / re if re else float("nan")
            out_rows.append({
                "sample_name": name,
                "lsdtt_erate_gcm2yr": f"{le:.10g}",
                "riversand_erate_gcm2yr": f"{re:.10g}",
                "pct_diff_lsdtt_minus_riversand": f"{pct:.6g}",
                "scheme": args.scheme,
                "dataset": dataset,
                "run_date_utc": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
                "git_sha": rcv.git_sha(),
            })

        summary_path = pdir / f"{dataset}_riversand_summary.csv"
        if args.freeze:
            write_frozen_summary(summary_path, out_rows, dataset, args.scheme)
            print(f"REFROZE riversand summary: {summary_path}")
            return EXIT_OK

        return check_against_frozen(out_rows, summary_path)
    except rcv.SkipError as exc:
        print(f"SKIP: {exc}")
        return EXIT_SKIP
    finally:
        if args.keep:
            print(f"--keep set: leaving {workdir}")
        else:
            shutil.rmtree(workdir, ignore_errors=True)
            print(f"[{dataset}] cleaned up {workdir} (exists={workdir.exists()})")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("dataset", nargs="?", default="dethier2014",
                    help="dataset name (default dethier2014)")
    ap.add_argument("--published-dir")
    ap.add_argument("--exe", help="path to lsdtt-cosmo-tool")
    ap.add_argument("--fetch-exe", help="path to lsdtt-fetch-raster")
    ap.add_argument("--samples", default="S169WTS035",
                    help="comma-separated sample_name list (default S169WTS035)")
    ap.add_argument("--scheme", default="LSDn",
                    help="metadata label for the riversand scheme in the summary")
    ap.add_argument("--riversand-cmd",
                    help="command to run riversand; placeholders: {dataset} {workdir} {dem} {outcsv} {points}")
    ap.add_argument("--riversand-csv",
                    help="path to precomputed riversand CSV (alternative to --riversand-cmd)")
    ap.add_argument("--riversand-key-col", default="sample_name",
                    help="key column in riversand CSV (default sample_name)")
    ap.add_argument("--riversand-rate-col", default="riversand_erate_gcm2yr",
                    help="rate column in riversand CSV (default riversand_erate_gcm2yr)")
    ap.add_argument("--basin-exe",
                    help="path to lsdtt-basin-extraction for built-in riversand mode")
    ap.add_argument("--basin-threshold-pixels", type=int, default=250,
                    help="channel threshold used in built-in basin extraction (default 250)")
    ap.add_argument("--riversand-bins-m", type=int, default=500,
                    help="elevation bin size for riversand process_single_catchment (default 500 m)")
    ap.add_argument("--riversand-scaling", default="LSDn",
                    help="riversand scaling for built-in mode (default LSDn)")
    ap.add_argument("--freeze", action="store_true",
                    help="regenerate tracked <dataset>_riversand_summary.csv")
    ap.add_argument("--keep", action="store_true", help="keep temporary workdir")
    ap.add_argument("--self-test", action="store_true",
                    help="offline harness self-test")
    args = ap.parse_args()

    if args.self_test:
        return run_self_test(args)
    return run_mode(args)


if __name__ == "__main__":
    sys.exit(main())
