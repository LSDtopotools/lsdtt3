#!/usr/bin/env python3
"""Fail if any built executable is older than a source it was built from.

WHY THIS EXISTS

A build system will happily run yesterday's binary, so "the test passed" and
"the code passed" are different statements unless the binary is known to be
current. A stale binary does not error -- it produces a confident green, which
is the worst available failure mode for a test suite.

Both halves of that bit this project on 2026-09-10:

  * the parameter-convention baseline was generated against a tree in which ten
    CLI binaries were older than their source and one had never been built. It
    recorded two violations the source had already fixed and missed nine that
    were really there -- and every error pointed the same way, making the guard
    look greener than the tree was;

  * a CLI smoke test passed against an executable built before a function
    signature changed, while a full build was at that moment FAILING on two call
    sites in that same file.

`run_cli_smoke.py` now checks its own executable, which covers the CLI smoke
tests. This covers everything else -- in particular the ~60 C++ test drivers,
where a stale driver silently runs old object code and reports success.

The manifest is generated by CMake at generate time from its own list of
executable targets, so a target added later is covered without anyone having to
remember this file exists.

A target that has not been built at all is reported separately: that is a normal
state during a partial build, but it means the target is UNCHECKED, so it is
named rather than passed over in silence. It is not fatal on its own; only a
stale binary is.
"""

from __future__ import annotations

import argparse
import pathlib
import sys


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--manifest", required=True, type=pathlib.Path)
    ap.add_argument(
        "--allow-missing",
        action="store_true",
        default=True,
        help="Do not fail on targets that have never been built (default).",
    )
    args = ap.parse_args()

    if not args.manifest.is_file():
        print(f"ERROR: manifest not found: {args.manifest}", file=sys.stderr)
        return 2

    stale: list[tuple[str, str, str, float]] = []
    missing: list[str] = []
    checked = 0

    for line in args.manifest.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        parts = line.split("\t")
        if len(parts) != 3:
            print(f"ERROR: malformed manifest line: {line!r}", file=sys.stderr)
            return 2
        target, exe_path, joined_sources = parts

        exe = pathlib.Path(exe_path)
        if not exe.is_file():
            missing.append(target)
            continue

        exe_mtime = exe.stat().st_mtime
        checked += 1

        for src in joined_sources.split("|"):
            if not src:
                continue
            source = pathlib.Path(src)
            if not source.is_file():
                # A generated source that no longer exists is not this test's
                # business; the build would have failed already.
                continue
            src_mtime = source.stat().st_mtime
            if exe_mtime < src_mtime:
                stale.append((target, exe_path, src, src_mtime - exe_mtime))
                break

    print(f"build currency: {checked} executable(s) checked, "
          f"{len(missing)} not built, {len(stale)} STALE")

    if missing:
        print(f"\nNOT BUILT ({len(missing)}) -- these targets are UNCHECKED by "
              f"any test that runs them:")
        for target in sorted(missing):
            print(f"    {target}")

    if stale:
        print(f"\nSTALE ({len(stale)}) -- the binary is older than its source, "
              f"so any test running it reports on code that is no longer in the "
              f"tree:", file=sys.stderr)
        for target, exe_path, src, behind in sorted(stale):
            print(f"    {target}", file=sys.stderr)
            print(f"        binary  : {exe_path}", file=sys.stderr)
            print(f"        older than: {src}", file=sys.stderr)
            print(f"        by      : {behind:.0f} s", file=sys.stderr)
        print("\nRebuild before trusting any result:  cmake --build <build dir>",
              file=sys.stderr)
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
