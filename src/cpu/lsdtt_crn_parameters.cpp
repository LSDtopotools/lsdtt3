// ---------------------------------------------------------------------------
// CRONUS v3 muon emulator (2026-08-01)
//
// Coefficients of a three-exponential fit to the Balco CRONUS v3 TABULATED
// model-1A muon inventory (crn_reference/v3/data/Nmu.mat v3.2, frozen at
// tests/expected/cosmo/balco_v3_nmu_reference.csv).  This is the inventory v3's
// erosion-rate root-find actually interpolates (get_erates_v3.m:155 for St,
// :268 for LSDn) -- NOT the single-exponential approximation the removed
// balcoCRONUSv3/PD schemes reproduced.
//
// Model, with x = (p_hPa - 1013.25)/100:
//   log P_k(x) = a_k0 + a_k1 x + a_k2 x^2       [atoms g^-1 yr^-1]
//   log D_k(x) = b_k0 + b_k1 x + b_k2 x^2       [g cm^-2]
//   Lambda_1 = D_1;  Lambda_2 = Lambda_1 + D_2;  Lambda_3 = Lambda_2 + D_3
//   N_mu(eps,p) = sum_k P_k(p) Lambda_k(p) / (eps + Lambda_k(p) lambda)
//
// The cumulative form guarantees Lambda_1 < Lambda_2 < Lambda_3 at every
// pressure, so the pathway ordering never swaps as p varies.
//
// Fit quality vs the table over 450-1020 hPa x 2.7e-6..2.7 g cm^-2 yr^-1
// (tests/expected/cosmo/cronus_muon_emulator_fit_report.csv, variant 'free'):
//   Be10 max |rel| 0.772%, Al26 0.870%, C14 1.153%.
//
// Generated by python_helpers/fit_cronus_muon_emulator.py.  Do not hand-edit:
// regenerate and re-freeze the report if these ever change.
// ---------------------------------------------------------------------------
