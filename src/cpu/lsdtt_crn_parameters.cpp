// NOTE: balco_cronus_v3_lambda_mu_eff() -- Lambda_mu(p) = 1/(0.01036 -
// 9.697e-6 p), Balco (2017, QG 39, Eq. 8) -- was REMOVED on 2026-08-01 along
// with the balcoCRONUSv3/balcoCRONUSv3PD schemes.  It is a NEAR-SURFACE
// effective attenuation length (so described at make_consts_v3.m:211), but an
// eroding column integrates muon production to a depth of order epsilon/lambda
// -- kilometres of rock -- where the deep fast-muon tail dominates.  Measured
// against v3's own tabulated inventory it is too short by 1.7x at sea level and
// 4.6x at 900 hPa.  Do not reintroduce it for erosion-rate work.

double lsdtt_crn_parameters::balco_cronus_v3_muon_surface_production(
    double pressure_mbar,
    double p_mu_slhl,
    double l_mu_atm_mbar)
{
    if (!std::isfinite(pressure_mbar))
        throw std::invalid_argument("muon_surface_production: pressure_mbar must be finite");
    if (!std::isfinite(p_mu_slhl) || p_mu_slhl < 0.0)
        throw std::invalid_argument("muon_surface_production: p_mu_slhl must be finite and >= 0");
    if (!std::isfinite(l_mu_atm_mbar) || l_mu_atm_mbar <= 0.0)
        throw std::invalid_argument("muon_surface_production: l_mu_atm_mbar must be finite and > 0");

    // CRONUS v3 / Balco (2017, QG 39, Eq. 7):
    //   P_mu,0(h) = P_mu,SL * exp((1013.25 - h) / L_mu_atm).
    return p_mu_slhl * std::exp((1013.25 - pressure_mbar) / l_mu_atm_mbar);
}

bool lsdtt_crn_parameters::is_valid_muon_scheme(const std::string& muon_scheme)
{
    for (const char* scheme : kMuonSchemes)
    {
        if (muon_scheme == scheme)
            return true;
    }
    return false;
}

std::string lsdtt_crn_parameters::allowed_muon_schemes_csv()
{
    std::string out;
    for (std::size_t i = 0; i < sizeof(kMuonSchemes)/sizeof(kMuonSchemes[0]); ++i)
    {
        if (i > 0)
            out += ", ";
        out += kMuonSchemes[i];
    }
    return out;
}



//
// Fitted emulator evaluated at one site.  Allocation-free: six std::exp calls
// and no container touched, so it is safe and cheap inside an OpenMP loop.
CronusEmulatorTerms lsdtt_crn_parameters::cronus_emulator_terms(
    const std::string& nuclide, double P_mbar, bool lsdn,
    double lsdn_slhl_reference)
{
    if (!std::isfinite(P_mbar))
        throw std::invalid_argument("cronus emulator: P_mbar must be finite");

    const int n = emu_nuclide_index(nuclide);

    double p0_sp;
    if (lsdn)
    {
        if (!std::isfinite(lsdn_slhl_reference) || lsdn_slhl_reference <= 0.0)
            throw std::invalid_argument(
                "cronus emulator: lsdn_slhl_reference must be finite and > 0");
        p0_sp = lsdn_slhl_reference * kEmuRefPLSDn[n];
    }
    else
    {
        p0_sp = kEmuRefPSt[n];
    }

    // Clamp exactly as v3's intNmu.m does, rather than extrapolating the fit.
    double p = P_mbar;
    if (p < kEmuPMin) p = kEmuPMin;
    if (p > kEmuPMax) p = kEmuPMax;
    const double x = (p - 1013.25) / 100.0;

    double P[3], D[3];
    for (int k = 0; k < 3; ++k)
    {
        const double* a = kEmuA[n][k];
        const double* b = kEmuB[n][k];
        P[k] = std::exp(a[0] + a[1] * x + a[2] * x * x);
        D[k] = std::exp(b[0] + b[1] * x + b[2] * x * x);
    }

    CronusEmulatorTerms out;
    out.lambda = kEmuLambda[n];
    out.gamma_sp = 160.0;         // Lsp.m:5
    out.p0_spallation = p0_sp;
    out.gamma_mu[0] = D[0];
    out.gamma_mu[1] = out.gamma_mu[0] + D[1];
    out.gamma_mu[2] = out.gamma_mu[1] + D[2];
    out.p_mu[0] = P[0];
    out.p_mu[1] = P[1];
    out.p_mu[2] = P[2];
    return out;
}

//
// Shared muon half of the CRONUS emulator.  Fills Gamma_[1..3] and returns the
// three surface muon production rates P_k(p); the caller supplies the
// spallation production, which is all that differs between St and LSDn.
void lsdtt_crn_parameters::set_cronus_emulator_common(const std::string& nuclide,
                                                       double P_mbar,
                                                       bool lsdn,
                                                       double lsdn_slhl_reference)
{
    const int n = emu_nuclide_index(nuclide);
    const CronusEmulatorTerms e =
        cronus_emulator_terms(nuclide, P_mbar, lsdn, lsdn_slhl_reference);

    Gamma_[0] = e.gamma_sp;
    Gamma_[1] = e.gamma_mu[0];
    Gamma_[2] = e.gamma_mu[1];
    Gamma_[3] = e.gamma_mu[2];

    // Only the requested nuclide's decay constant is meaningful here: the
    // fitted Gamma_ values are nuclide-specific, so one instance serves one
    // nuclide.  The others keep their constructor defaults.
    if (n == 0)      lambda_10Be_ = e.lambda;
    else if (n == 1) lambda_26Al_ = e.lambda;
    else             lambda_14C_  = e.lambda;

    const double p0 = e.p0_spallation + e.p_mu[0] + e.p_mu[1] + e.p_mu[2];
    double* F = (n == 0) ? F_10Be_ : (n == 1) ? F_26Al_ : F_14C_;
    F[0] = e.p0_spallation / p0;
    F[1] = e.p_mu[0] / p0;
    F[2] = e.p_mu[1] / p0;
    F[3] = e.p_mu[2] / p0;

    if (n == 0)      P0_10Be_ = p0;
    else if (n == 1) P0_26Al_ = p0;
    else             P0_14C_  = p0;
}

//
// CRONUS v3 emulator, Stone/Lal (St) spallation scaling.
//
// P_mbar is the SITE pressure; the muon terms are pressure-dependent, so this
// must be called per pixel (or per sample) rather than once per run.
//
// IMPORTANT: v3 applies topographic/thickness shielding and the spallation
// scaling factor to the SPALLATION term only -- intNmu(eps, pressure) takes no
// shielding and no scaling argument (get_erates_v3.m:117,155).  The caller is
// responsible for that split; do NOT pass the result of this setter through
// scale_F_values(), which would apply the Vermeesch redistribution to the muon
// pathways as well and break the emulation.
void lsdtt_crn_parameters::set_cronus_emulator_st_parameters(
    const std::string& nuclide, double P_mbar)
{
    set_cronus_emulator_common(nuclide, P_mbar, /*lsdn=*/false, 0.0);
}

//
// CRONUS v3 emulator, LSDn spallation scaling.
//
// lsdn_slhl_reference is the raw LSDn grid value at SLHL (Rc = 0 GV,
// P = 1013.25 hPa, S = S_ref) for this nuclide -- obtain it from
// cronus_emulator_lsdn_slhl_reference().  It is needed because v3 multiplies
// consts.refP_LSDn by the RAW LSDn scaling factor while lsdtt3's lsdn_scaling()
// is SLHL-normalised to 1, so the equivalent lsdtt3 SLHL production is
// lsdn_slhl_reference * refP_LSDn.
//
// The muon terms are identical to the St case: v3's erosion-rate root-find
// calls the same intNmu for St, Lm and LSDn (get_erates_v3.m:155 and :268), so
// the muon inventory carries no dependence on the spallation scaling scheme.
void lsdtt_crn_parameters::set_cronus_emulator_lsdn_parameters(
    const std::string& nuclide, double P_mbar, double lsdn_slhl_reference)
{
    set_cronus_emulator_common(nuclide, P_mbar, /*lsdn=*/true,
                               lsdn_slhl_reference);
}

//
// Raw LSDn grid value at SLHL for one nuclide: Rc = 0 GV, P = 1013.25 hPa,
// S = S_ref.  This is the quantity lsdn_scaling() divides by, so multiplying it
// back in converts lsdtt3's SLHL-normalised scaling into v3's raw convention.
double lsdtt_crn_parameters::cronus_emulator_lsdn_slhl_reference(
    const CrnNcData& nc, const std::string& nuclide)
{
    if (!nc.lsdn_loaded || nc.lsdn_sphi.empty())
        throw std::runtime_error(
            "cronus_emulator_lsdn_slhl_reference: the loaded crn_parameters.nc "
            "has no LSDn scaling grids");
    const double ref = lsdn_grid_value(nc, nuclide, 0.0, 1013.25, nc.lsdn_sphi[0]);
    if (!(ref > 0.0))
        throw std::runtime_error(
            "cronus_emulator_lsdn_slhl_reference: non-positive SLHL reference for \""
            + nuclide + "\"");
    return ref;
}

// 
void lsdtt_crn_parameters::reset_scaling(const std::string& muon_scheme)
{
    if      (muon_scheme == "Braucher")          set_braucher_parameters();
    else if (muon_scheme == "BraucherBorchers")  set_braucher_borchers_parameters();
    else if (muon_scheme == "Granger")           set_granger_parameters();
    else if (muon_scheme == "Schaller")          set_schaller_parameters();
    else if (muon_scheme == "newCRONUS")         set_new_cronus_parameters();
    else if (muon_scheme == "cronusEmulatorSt" ||
             muon_scheme == "cronusEmulatorLSDn")
    {
        // Deliberately not serviceable here.  The emulator's muon terms depend
        // on the site pressure AND the nuclide, neither of which reset_scaling()
        // receives, so there is no correct thing to set.  Failing loudly beats
        // silently installing sea-level Be10 parameters for some other case.
        throw std::invalid_argument(
            "muon scheme \"" + muon_scheme + "\" is pressure- and "
            "nuclide-dependent and cannot be set through reset_scaling(). Call "
            "set_cronus_emulator_st_parameters(nuclide, P_mbar) or "
            "set_cronus_emulator_lsdn_parameters(nuclide, P_mbar, "
            "lsdn_slhl_reference) instead; the cosmo raster path does this per "
            "pixel.");
    }
    else
    {
        throw std::invalid_argument(
            "unknown muon scheme \"" + muon_scheme + "\". Allowed values: "
            + allowed_muon_schemes_csv());
    }
}

//
// scale_one_nuclide: Newton-Raphson to find effective depth x such that
//   Sigma_i F[i]*exp(-x/Gamma[i]) == total_shielding
// then rescale: F[i] *= exp(-x/Gamma[i]).
// This preserves the relative attenuation shape of each production pathway
// rather than applying a flat multiplier.
//
// total_shielding here is production scaling x topographic shielding, so it
// is routinely > 1 (Stone scaling exceeds 1 above a few hundred metres);
// the Vermeesch (2007) scheme handles that with a NEGATIVE effective depth
// (amplification, spallation amplified most).  Fix approved by Simon Mudd
// 2026-07-16: the previous ">= 1.0 -> return" guard silently dropped the
// production scaling at altitude, found by the CRONUS v3 comparison tests.
void lsdtt_crn_parameters::scale_one_nuclide(double total_shielding,
                                              const double Gamma[4],
                                              double F[4])
{
    if (total_shielding == 1.0)
        return;   // exactly neutral - nothing to do

    const double tolerance    = 1e-7;
    const double displace_x   = 1e-6;
    double x                  = 0.0;
    double x_change           = 1.0;

    while (std::fabs(x_change) > tolerance)
    {
        double s  = 0.0, sd = 0.0;
        for (int i = 0; i < 4; ++i)
        {
            s  += F[i] * std::exp(-x           / Gamma[i]);
            sd += F[i] * std::exp(-(x + displace_x) / Gamma[i]);
        }
        double fx        = s  - total_shielding;
        double fx_d      = sd - total_shielding;
        double deriv     = (fx_d - fx) / displace_x;
        if (deriv == 0.0) break;
        x_change = fx / deriv;
        x -= x_change;
    }

    for (int i = 0; i < 4; ++i)
        F[i] *= std::exp(-x / Gamma[i]);
}

// 
void lsdtt_crn_parameters::scale_F_values(double total_shielding,
                                           const std::string& nuclide)
{
    if (nuclide == "Be10")
        scale_one_nuclide(total_shielding, Gamma_, F_10Be_);
    else if (nuclide == "Al26")
        scale_one_nuclide(total_shielding, Gamma_, F_26Al_);
    else if (nuclide == "C14")
        scale_one_nuclide(total_shielding, Gamma_, F_14C_);
    else
    {
        std::cout << "lsdtt_crn_parameters::scale_F_values: unknown nuclide \""
                  << nuclide << "\". No scaling applied." << std::endl;
    }
}

// 
double lsdtt_crn_parameters::atmospheric_pressure_standard(double elevation_m)
{
    // Balco barometric formula with SLHL standard-atmosphere constants.
    // Returns pressure in mbar (hPa).
    const double gmr   = -0.03417;   // g*M/R (mol^-^1 K^-^1)
    const double dtdz  =  0.0065;    // environmental lapse rate (K m^-^1)
    const double P_slp =  1013.25;   // standard sea-level pressure (mbar)
    const double T_slp =  288.15;    // standard sea-level temperature (K)
    double T_site = T_slp - dtdz * elevation_m;
    if (T_site <= 0.0) T_site = 1.0;   // guard against unphysical elevations
    return P_slp * std::exp((gmr / dtdz) * (std::log(T_slp) - std::log(T_site)));
}

// 
// Stone (2000) spallation scaling.  Faithfully ported from LSDTopoTools2
// (Balco / Stone 2000 Table 1 coefficients).
// Stone (2000) Table 1 spallation factor at the seven index latitudes.
// ONE definition, used by stone2000sp() and by stone_basis_sf().  Both used to
// compute this independently with character-for-character identical
// expressions, which on the Stone+paleomag production path meant evaluating it
// twice per pixel.
inline void stone_ilat_sf(double P, double i_sf[7])
{
    static const double sa[7] = { 31.8518, 34.3699, 40.3153, 42.0983, 56.7733, 69.0720, 71.8733 };
    static const double sb[7] = { 250.3193, 258.4759, 308.9894, 512.6857, 649.1343, 832.4566, 863.1927 };
    static const double sc[7] = { -0.083393,-0.089807,-0.106248,-0.120551,-0.160859,-0.199252,-0.207069 };
    static const double sd[7] = { 7.4260e-5,7.9457e-5,9.4508e-5,1.1752e-4,1.5463e-4,1.9391e-4,2.0127e-4 };
    static const double se[7] = { -2.2397e-8,-2.3697e-8,-2.8234e-8,-3.8809e-8,-5.0330e-8,-6.3653e-8,-6.6043e-8 };

    const double P2 = P * P, P3 = P2 * P;
    const double eP = std::exp(-P / 150.0);
    for (int k = 0; k < 7; ++k)
        i_sf[k] = sa[k] + sb[k] * eP + sc[k] * P + sd[k] * P2 + se[k] * P3;
}

// Basis expansion from a PRECOMPUTED index-latitude table.
inline void stone_basis_sf_from_table(const double i_sf[7], double S[18])
{
    static const double ilat[7] = { 0.0, 10.0, 20.0, 30.0, 40.0, 50.0, 60.0 };

    S[0] = i_sf[6];                        // Rc = 0 carries the 60 deg value
    for (int k = 0; k < 7; ++k) S[1 + k] = i_sf[6 - k];

    // Log-log extension to 25 GV, fitted to the lat 0/10/20 points exactly as
    // stone_factor_at_rc does.
    // ilat[0] = 0 and ilat[2] = 20 are compile-time constants, as are log(16)
    // ... log(25), so all of these are loop- and call-invariant.  Hoisting them
    // is bit-identical (std::exp/std::log are deterministic for a fixed
    // argument) and removes ~14 transcendental calls per pixel from what is a
    // per-pixel path on the Stone paleomag production raster.
    static const double i_Rc0     = 14.3 * std::pow(std::cos(ilat[0] * kPi / 180.0), 4.0);
    static const double i_Rc2     = 14.3 * std::pow(std::cos(ilat[2] * kPi / 180.0), 4.0);
    static const double log_i_Rc0 = std::log(i_Rc0);
    static const double log_i_Rc2 = std::log(i_Rc2);
    static const double log_rc_ext[10] = {
        std::log(16.0), std::log(17.0), std::log(18.0), std::log(19.0),
        std::log(20.0), std::log(21.0), std::log(22.0), std::log(23.0),
        std::log(24.0), std::log(25.0)
    };

    const double log_i_sf0 = std::log(i_sf[0]);
    const double slope = (log_i_sf0 - std::log(i_sf[2]))
                       / (log_i_Rc0 - log_i_Rc2);
    for (int rc_ext = 16; rc_ext <= 25; ++rc_ext)
        S[8 + rc_ext - 16] = std::exp(log_i_sf0
                                      + slope * (log_rc_ext[rc_ext - 16] - log_i_Rc0));
}

// Stone (2000) geographic scaling from a PRECOMPUTED index-latitude table.
// Split out so the Stone+paleomag path can compute that table once per pixel
// instead of once in stone2000sp() and again in stone_basis_sf().
double stone2000sp_from_table(const double i_sf[7], double lat_deg,
                              double P_mbar, double Fsp)
{
    static const double ilat[7] = { 0.0, 10.0, 20.0, 30.0, 40.0, 50.0, 60.0 };
    // Muonic scaling constants at the 7 index latitudes
    static const double mk[7] = { 0.587, 0.600, 0.678, 0.833, 0.933, 1.000, 1.000 };

    // Invariant in k, so evaluated once rather than seven times.
    const double mu_atm = std::exp((1013.25 - P_mbar) / 242.0);

    double M_at_ilat[7];
    for (int k = 0; k < 7; ++k) M_at_ilat[k] = mk[k] * mu_atm;

    lat_deg = std::fabs(lat_deg);
    if (lat_deg > 60.0) lat_deg = 60.0;

    const double S = lsdtt_crn_parameters::interp1d_n(ilat, i_sf, 7, lat_deg);
    const double M = lsdtt_crn_parameters::interp1d_n(ilat, M_at_ilat, 7, lat_deg);

    return (S * Fsp) + (M * (1.0 - Fsp));
}

double lsdtt_crn_parameters::stone2000sp(double lat_deg,
                                          double P_mbar,
                                          double Fsp) const
{
    if (Fsp > 1.0) Fsp = 0.978;
    if (std::fabs(lat_deg) > 90.0)
    {
        std::cout << "stone2000sp: |latitude| > 90. Defaulting to 45 degrees." << std::endl;
        lat_deg = 45.0;
    }

    double i_sf[7];
    stone_ilat_sf(P_mbar, i_sf);
    return stone2000sp_from_table(i_sf, lat_deg, P_mbar, Fsp);
}

